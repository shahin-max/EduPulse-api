import { Transform, Type } from 'class-transformer';
import {
  IsBoolean,
  IsDate,
  IsIn,
  IsInt,
  IsOptional,
  IsString,
  Length,
  Matches,
  MaxLength,
  Min,
} from 'class-validator';
import {
  fee_invoices_status,
  payments_method,
} from '../../generated/prisma/enums.js';
import { PaginationQueryDto, toBoolean } from '../../common/pagination.js';
import { trim, upperTrim } from '../../common/validation.js';
import { MONEY_REGEX } from '../invoice-math.js';

const MONEY_MESSAGE =
  'must be an amount with at most 2 decimals, e.g. 1500 or 1500.50';
/** Accepts 1500, 1500.5 or "1500.50" and keeps it as a string for exact Decimal maths. */
const toMoneyString = ({ value }: { value: unknown }): unknown =>
  typeof value === 'number' ? String(value) : value;

export class CreateFeePlanDto {
  @IsInt()
  @Min(1)
  courseId: number;

  /** Optional: a plan for one batch of the course only. */
  @IsOptional()
  @IsInt()
  @Min(1)
  batchId?: number | null;

  /** @example "JEE 2027 - monthly fee" */
  @Transform(trim)
  @IsString()
  @Length(2, 160)
  title: string;

  /** ISO 4217 code; defaults to INR. */
  @IsOptional()
  @Transform(upperTrim)
  @Matches(/^[A-Z]{3}$/, {
    message: 'currency must be a 3-letter code such as INR',
  })
  currency?: string;

  /** @example "3500.00" */
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `amount ${MONEY_MESSAGE}` })
  amount: string;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;
}

export class UpdateFeePlanDto {
  @IsOptional()
  @IsInt()
  @Min(1)
  batchId?: number | null;

  @IsOptional()
  @Transform(trim)
  @IsString()
  @Length(2, 160)
  title?: string;

  @IsOptional()
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `amount ${MONEY_MESSAGE}` })
  amount?: string;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;
}

export class ListFeePlansQueryDto {
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  courseId?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  batchId?: number;

  @IsOptional()
  @Transform(toBoolean)
  @IsBoolean()
  activeOnly?: boolean;
}

export class CreateInvoiceDto {
  @IsInt()
  @Min(1)
  enrollmentId: number;

  /** Optional fee plan of the enrollment's course; supplies the default gross amount. */
  @IsOptional()
  @IsInt()
  @Min(1)
  feePlanId?: number;

  /** @example "April 2027 tuition" */
  @IsOptional()
  @Transform(trim)
  @IsString()
  @MaxLength(255)
  description?: string;

  /** Required unless a fee plan is given. */
  @IsOptional()
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `grossAmount ${MONEY_MESSAGE}` })
  grossAmount?: string;

  /** Scholarship or other discount; cannot exceed the gross amount. */
  @IsOptional()
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `discountAmount ${MONEY_MESSAGE}` })
  discountAmount?: string;

  @IsOptional()
  @Type(() => Date)
  @IsDate()
  dueDate?: Date;

  /** Issue straight away instead of creating a DRAFT. */
  @IsOptional()
  @IsBoolean()
  issue?: boolean;
}

/** Only DRAFT invoices can be edited. */
export class UpdateInvoiceDto {
  @IsOptional()
  @Transform(trim)
  @IsString()
  @MaxLength(255)
  description?: string;

  @IsOptional()
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `grossAmount ${MONEY_MESSAGE}` })
  grossAmount?: string;

  @IsOptional()
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `discountAmount ${MONEY_MESSAGE}` })
  discountAmount?: string;

  @IsOptional()
  @Type(() => Date)
  @IsDate()
  dueDate?: Date | null;
}

export class ListInvoicesQueryDto extends PaginationQueryDto {
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  enrollmentId?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  studentUserId?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  batchId?: number;

  @IsOptional()
  @IsIn(Object.values(fee_invoices_status))
  status?: fee_invoices_status;

  /** Only invoices with a due date before today and money still due. */
  @IsOptional()
  @Transform(toBoolean)
  @IsBoolean()
  overdue?: boolean;
}

export class RecordPaymentDto {
  /** @example "3500.00" */
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `amount ${MONEY_MESSAGE}` })
  amount: string;

  @IsIn(Object.values(payments_method))
  method: payments_method;

  /**
   * Unique per payment attempt (e.g. a UUID generated by the client). Re-sending the same
   * request returns the original payment instead of recording it twice.
   */
  @IsString()
  @Length(8, 100)
  idempotencyKey: string;

  /** CONFIRMED (default) for money received; PENDING for e.g. an uncleared cheque or bank transfer. */
  @IsOptional()
  @IsIn(['PENDING', 'CONFIRMED'])
  status?: 'PENDING' | 'CONFIRMED';

  /** e.g. "razorpay", "hdfc" */
  @IsOptional()
  @Transform(trim)
  @IsString()
  @MaxLength(40)
  provider?: string;

  /** UPI / bank / gateway transaction reference. */
  @IsOptional()
  @Transform(trim)
  @IsString()
  @MaxLength(120)
  externalReference?: string;

  /** When the money was received; defaults to now for confirmed payments. */
  @IsOptional()
  @Type(() => Date)
  @IsDate()
  paidAt?: Date;

  @IsOptional()
  @IsString()
  @MaxLength(5000)
  notes?: string;
}

export class UpdatePaymentStatusDto {
  /** A PENDING payment becomes CONFIRMED, FAILED or CANCELLED. */
  @IsIn(['CONFIRMED', 'FAILED', 'CANCELLED'])
  status: 'CONFIRMED' | 'FAILED' | 'CANCELLED';

  @IsOptional()
  @Type(() => Date)
  @IsDate()
  paidAt?: Date;
}

export class CreateRefundDto {
  @Transform(toMoneyString)
  @Matches(MONEY_REGEX, { message: `amount ${MONEY_MESSAGE}` })
  amount: string;

  @Transform(trim)
  @IsString()
  @Length(3, 500)
  reason: string;

  @IsString()
  @Length(8, 100)
  idempotencyKey: string;

  /** CONFIRMED (default) when the money has been returned; PENDING while in progress. */
  @IsOptional()
  @IsIn(['PENDING', 'CONFIRMED'])
  status?: 'PENDING' | 'CONFIRMED';

  @IsOptional()
  @Transform(trim)
  @IsString()
  @MaxLength(120)
  externalReference?: string;
}

export class UpdateRefundStatusDto {
  @IsIn(['CONFIRMED', 'FAILED', 'CANCELLED'])
  status: 'CONFIRMED' | 'FAILED' | 'CANCELLED';
}
