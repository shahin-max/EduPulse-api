import { Prisma } from '../generated/prisma/client.js';
import type {
  fee_invoices_status,
  payment_refunds_status,
  payments_status,
} from '../generated/prisma/enums.js';

type Decimal = Prisma.Decimal;
const ZERO = new Prisma.Decimal(0);

export interface InvoiceMoney {
  status: fee_invoices_status;
  gross_amount: Decimal;
  discount_amount: Decimal;
}

export interface PaymentMoney {
  amount: Decimal;
  status: payments_status;
  payment_refunds?: { amount: Decimal; status: payment_refunds_status }[];
}

export function sum(values: Decimal[]): Decimal {
  return values.reduce((total, value) => total.plus(value), ZERO);
}

/** Confirmed payments minus confirmed refunds of those payments. */
export function netPaid(payments: PaymentMoney[]): Decimal {
  const paid = sum(
    payments.filter((p) => p.status === 'CONFIRMED').map((p) => p.amount),
  );
  const refunded = sum(
    payments.flatMap((p) =>
      (p.payment_refunds ?? [])
        .filter((r) => r.status === 'CONFIRMED')
        .map((r) => r.amount),
    ),
  );
  return paid.minus(refunded);
}

/**
 * The fee_invoices.amount_due column is GENERATED by MySQL as gross - discount (the payable
 * amount). What is still owed is derived here:
 *   paid       = confirmed payments - confirmed refunds
 *   balanceDue = gross - discount - paid
 * Status: DRAFT and VOID are set explicitly and never derived. For issued invoices:
 * nothing (net) paid -> ISSUED, something paid -> PART_PAID, fully paid -> PAID.
 */
export function invoiceState(
  invoice: InvoiceMoney,
  payments: PaymentMoney[],
): { paid: Decimal; balanceDue: Decimal; status: fee_invoices_status } {
  const payable = invoice.gross_amount.minus(invoice.discount_amount);
  const paid = netPaid(payments);
  const balanceDue = payable.minus(paid);
  if (invoice.status === 'DRAFT' || invoice.status === 'VOID')
    return { paid, balanceDue, status: invoice.status };
  const status: fee_invoices_status = paid.lte(0)
    ? 'ISSUED'
    : balanceDue.lte(0)
      ? 'PAID'
      : 'PART_PAID';
  return { paid, balanceDue, status };
}

/** Money strings from DTOs: up to 10 integer digits and 2 decimals. */
export const MONEY_REGEX = /^\d{1,10}(\.\d{1,2})?$/;

export function money(value: string | number): Decimal {
  return new Prisma.Decimal(value).toDecimalPlaces(2);
}

/** Indian financial year (April to March, in IST) of a moment, as document_sequences stores it: "2026-27". */
export function fiscalYear(at: Date): string {
  const ist = new Date(at.getTime() + 330 * 60_000);
  const start =
    ist.getUTCMonth() >= 3 ? ist.getUTCFullYear() : ist.getUTCFullYear() - 1;
  return `${start}-${String((start + 1) % 100).padStart(2, '0')}`;
}

/**
 * "ALG/26-27/0001": the branch prefix, the financial year and a per-branch, per-year sequence
 * (consecutive, as GST invoices require; at least 4 digits). With a prefix of up to 5 characters the
 * number fits GST's 16-character limit until the sequence passes 9999.
 */
export function sequenceNumber(
  prefix: string,
  fy: string,
  value: number,
): string {
  return `${prefix}/${fy.slice(2)}/${String(value).padStart(4, '0')}`;
}

/** Drafts get a placeholder; the real number is taken when the invoice is issued, so discarded drafts leave no gaps. */
export const draftInvoiceNumber = (id: bigint) => `DRAFT-${id}`;
